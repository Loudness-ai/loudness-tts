// Builds the package: generated sources (version, voice catalogue), TypeScript, the espeak-ng WebAssembly module and data.
//   node scripts/build.mjs            (the WebAssembly module itself is built by espeak/build.sh)
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const pkg = JSON.parse(readFileSync(root + "package.json", "utf8"));
const catalog = readFileSync(root + "../python/src/local_tts/data/voices.json", "utf8");

writeFileSync(root + "src/version.ts", "// Generated by scripts/build.mjs.\n"
  + `export const VERSION = ${JSON.stringify(pkg.version)};\n`
  + `export const ORT_VERSION = ${JSON.stringify(pkg.dependencies["onnxruntime-web"])};\n`);
writeFileSync(root + "src/voices-data.ts", "// Generated by scripts/build.mjs from the Python edition's catalogue (local_tts/data/voices.json).\n"
  + "import type { CatalogData } from \"./catalog.js\";\n"
  + `const data: CatalogData = JSON.parse(${JSON.stringify(JSON.stringify(JSON.parse(catalog)))});\nexport default data;\n`);

if (!existsSync(root + "espeak-ng-data/phondata")) {
  throw new Error("espeak-ng-data is missing: run node scripts/espeak-data.mjs first.");
}
for (const [from, to] of [["../LICENSE", "LICENSE"], ["../NOTICE", "NOTICE"], ["../python/LICENSE-APACHE", "LICENSE-APACHE"]]) {
  cpSync(root + from, root + to);
}
rmSync(root + "dist", { recursive: true, force: true });
execFileSync(process.execPath, [root + "node_modules/typescript/bin/tsc", "-p", root], { stdio: "inherit" });
mkdirSync(root + "dist/wasm", { recursive: true });
cpSync(root + "src/wasm/espeak.mjs", root + "dist/wasm/espeak.mjs");
cpSync(root + "src/wasm/espeak.d.mts", root + "dist/wasm/espeak.d.mts");
console.log(`local-tts ${pkg.version} built.`);
